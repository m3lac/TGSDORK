import fs from 'node:fs';
import path from 'node:path';
import { getTaskDir } from '../core/checkpoint.js';
import type { TaskState, SourceItem } from '../types/index.js';

function sourceToBibtex(item: SourceItem, index: number): string {
  let hostname = '';
  try {
    hostname = new URL(item.url).hostname.replace(/^www\./, '');
  } catch {
    hostname = 'academic';
  }

  const key = `ref_${item.authors?.[0]?.toLowerCase() || hostname.split('.')[0]}_${item.year || '2024'}_${index + 1}`
    .replace(/[^a-zA-Z0-9_]/g, '');

  const author = item.authors && item.authors.length > 0
    ? item.authors.join(' and ')
    : hostname.split('.')[0].toUpperCase();

  const title = item.title.replace(/[{}\\]/g, '').trim() || 'Publikasi Ilmiah';
  const year = item.year || new Date().getFullYear().toString();

  return `@article{${key},
  author = {${author}},
  title = {${title}},
  journal = {${hostname}},
  year = {${year}},
  url = {${item.url}},
  note = {Diakses melalui TGSDORK}
}`;
}

export function exportToBibtex(state: TaskState): string {
  const bibEntries = state.sources.map((src, i) => sourceToBibtex(src, i));
  const content = `% BibTeX generated by TGSDORK for: ${state.topic}\n\n` + bibEntries.join('\n\n') + '\n';

  const taskDir = getTaskDir(state.id);
  const filePath = path.join(taskDir, 'references.bib');
  fs.writeFileSync(filePath, content, 'utf-8');
  return filePath;
}
