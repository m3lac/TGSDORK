/**
 * Ekstrak nama institusi / universitas Indonesia dari URL.
 * Mendukung seluruh domain *.ac.id maupun portal akademik nasional.
 */
export function resolveIndonesianInstitution(urlStr: string): string | undefined {
  if (!urlStr) return undefined;
  let hostname = '';
  try {
    hostname = new URL(urlStr).hostname.toLowerCase().replace(/^www\./, '');
  } catch {
    return undefined;
  }

  // 1. Cek exact atau parent domain match di daftar kampus nasional
  for (const [domain, name] of Object.entries(INDONESIAN_CAMPUS_DOMAINS)) {
    if (hostname === domain || hostname.endsWith('.' + domain)) {
      return name;
    }
  }

  // 2. Fallback cerdas untuk seluruh domain .ac.id lain di Indonesia (PTN/PTS/STIKES/Poltek)
  const acIdMatch = hostname.match(/([a-z0-9-]+)\.ac\.id$/);
  if (acIdMatch) {
    const slug = acIdMatch[1].toUpperCase();
    return `Repositori Akademik ${slug} (${acIdMatch[1]}.ac.id)`;
  }

  return undefined;
}
